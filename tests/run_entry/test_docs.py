def test_generator_check_passes():
    r = subprocess.run([sys.executable, os.path.join(ROOT, 'tools', 'run_input_table.py'), '--check'],
                       capture_output=True, text=True)
    assert r.returncode == 0, r.stdout + r.stderr


def test_every_schema_key_is_in_the_manual_and_vice_versa():
    assert rit.coverage_problems(doc_text()) == []
    raw, doc = rit.raw_leaves(), rit.doc_leaves(doc_text())
    assert set(raw) == set(doc) and len(doc) == len(raw)
    assert len(raw) > 100                                          # the walk really reaches the stage and field variants


def test_every_generated_table_is_marked_in_the_manual():
    text = doc_text()
    for name in rit.TABLES:
        assert rit.BEGIN.format(name) in text and rit.END.format(name) in text, name


def test_a_schema_key_without_a_description_fails(monkeypatch):
    desc = dict(rit.DESC)
    desc.pop('run.seed')
    monkeypatch.setattr(rit, 'DESC', desc)
    assert any('run.seed' in p for p in rit.coverage_problems(doc_text()))
    with pytest.raises(SystemExit):
        rit.render('run')


def test_a_new_schema_key_must_be_documented(monkeypatch):
    monkeypatch.setitem(run_input.SCHEMA['run'].fields, 'brand_new', run_input.V('int', default=0))
    problems = rit.coverage_problems(doc_text())
    assert any('run.brand_new' in p for p in problems)
    with pytest.raises(SystemExit):
        rit.render('run')


def test_a_changed_default_makes_the_manual_stale(monkeypatch):
    monkeypatch.setitem(run_input.SCHEMA['run'].fields, 'seed', run_input.V('int', default=7))
    text = doc_text()
    assert rit.rewrite(text) != text


