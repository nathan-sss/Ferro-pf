"""RUN-ENTRY E5 (SPEC § 16.5): docs/RUN_INPUT.md and docs/run_examples/ cannot drift from the code.

Marker convention of the manual (the info string of a code fence):
    ```toml complete   a whole input file: must load, pass the builder precheck and the CLI `check`
    ```toml            a fragment: must be valid TOML
    ```python run      a script: must run to the end in a fresh process
Any other fence (plain, text) is not checked.  The key tables between `run_input_table` markers are generated by
tools/run_input_table.py and checked here against the schema.
"""
import ast
import glob
import os
import re
import subprocess
import sys
import tomllib

for name in ('OPENBLAS_NUM_THREADS', 'MKL_NUM_THREADS', 'VECLIB_MAXIMUM_THREADS'):
    os.environ[name] = '1'
os.environ.setdefault('MPLBACKEND', 'Agg')
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(ROOT, 'tools'))

import pytest

import run_input_table as rit
from fftpf import run_builder, run_input

DOC = os.path.join(ROOT, 'docs', 'RUN_INPUT.md')
EXAMPLES = sorted(glob.glob(os.path.join(ROOT, 'docs', 'run_examples', '*.toml')))
FENCE = re.compile(r'^```(\S+)(?: (\S+))?\n(.*?)^```$', re.S | re.M)


def doc_text():
    with open(DOC, encoding='utf-8') as fh:
        return fh.read()


def fences(kind, tag=None):
    return [(m.start(), m.group(3)) for m in FENCE.finditer(doc_text()) if m.group(1) == kind and m.group(2) == tag]


def cli(command, path, cwd=None):
    env = dict(os.environ, PYTHONPATH=ROOT)
    return subprocess.run([sys.executable, '-m', 'fftpf', command, str(path)], capture_output=True, text=True, env=env,
                          cwd=cwd or ROOT)


