# --------------------------------------------------------------------------- the fenced blocks of the manual

def test_the_manual_has_complete_files_and_they_pass_check(tmp_path):
    blocks = fences('toml', 'complete')
    assert blocks, 'the manual shows no complete input file'
    for i, (_, text) in enumerate(blocks):
        path = tmp_path / f'block_{i}.toml'
        path.write_text(text)
        cfg = run_input.load(str(path))
        run_builder.precheck(cfg)
        r = cli('check', path)
        assert r.returncode == 0, (i, r.stderr)


def test_every_toml_fragment_is_valid_toml():
    plain = fences('toml', None)
    assert plain
    for _, text in plain + fences('toml', 'complete'):
        tomllib.loads(text)


def test_the_python_blocks_run(tmp_path):
    blocks = fences('python', 'run')
    assert blocks, 'the manual shows no script'
    env = dict(os.environ, PYTHONPATH=ROOT)
    for i, (_, text) in enumerate(blocks):
        script = tmp_path / f'script_{i}.py'
        script.write_text(text)
        r = subprocess.run([sys.executable, str(script)], capture_output=True, text=True, env=env, cwd=tmp_path)
        assert r.returncode == 0, r.stderr
        assert 'True (3, 16, 16)' in r.stdout, r.stdout


# --------------------------------------------------------------------------- the refusals of the code are in the manual

CODE = ('run_input.py', 'run_builder.py', 'run_output.py', 'run_protocol.py', 'run_measure.py')


def _leading(node):
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.JoinedStr):
        return ''.join(v.value if isinstance(v, ast.Constant) else '{}' for v in node.values)
    return None


def refusal_paths():
    """The key paths named at the refusal sites of the entry layer: _err(path, ...), yield path, reason, ConfigError("path: ...")."""
    found = set()
    for name in CODE:
        tree = ast.parse(open(os.path.join(ROOT, 'fftpf', name), encoding='utf-8').read())
        for node in ast.walk(tree):
            text = None
            if isinstance(node, ast.Call):
                f = node.func
                fname = f.id if isinstance(f, ast.Name) else (f.attr if isinstance(f, ast.Attribute) else None)
                if fname == '_err' and node.args:
                    text = _leading(node.args[0])
                elif fname == 'ConfigError' and node.args:
                    text = (_leading(node.args[0]) or '').split(':')[0]
            elif isinstance(node, ast.Yield) and isinstance(node.value, ast.Tuple) and node.value.elts:
                text = _leading(node.value.elts[0])
            if text:
                found.add(text)
    out = set()
    for text in found:
        norm = re.sub(r'\[[^\]]*\]', '[]', text)
        if '{' in norm or not re.match(r'^[A-Za-z_]+[\w.\[\]]*$', norm) or norm == '<root>':
            continue                                   # a path built from a variable: not literal at the site
        out.add(re.sub(r'\[\]$', '', norm))
    return out


def test_every_key_path_a_refusal_names_occurs_in_the_refusals_section():
    text = doc_text()
    section = text[text.index('## 9 Refusals'):text.index('## 10 ')]
    squashed = re.sub(r'\[[^\]]*\]', '[]', section)
    paths = refusal_paths()
    assert len(paths) > 20
    missing = sorted(p for p in paths if p not in squashed)
    assert not missing, f'refusal sites name key paths the manual\'s section 9 never mentions: {missing}'


# --------------------------------------------------------------------------- docs/CAPABILITIES.md section 8

def test_capabilities_section_8_names_tests_that_exist():
    text = open(os.path.join(ROOT, 'docs', 'CAPABILITIES.md'), encoding='utf-8').read()
    section = text[text.index('## §8 Running from an input file'):]
    assert 'No CORE gate item covers the entry layer' in section
    here, current, checked = os.path.dirname(os.path.abspath(__file__)), None, 0
    for span in re.findall(r'`([^`]+)`', section):
        m = re.match(r'^(test_\w+\.py)(?:::(\w+))?$', span) or re.match(r'^()::(\w+)$', span)
        if not m:
            continue
        current = m.group(1) or current
        path = os.path.join(here, current)
        assert os.path.isfile(path), span
        if m.group(2):
            assert re.search(rf'^def {m.group(2)}\b', open(path, encoding='utf-8').read(), re.M), span
        checked += 1
    assert checked > 30
    for name in re.findall(r'`(0\d)`', section):                  # example numbers quoted in the table
        assert glob.glob(os.path.join(ROOT, 'docs', 'run_examples', f'{name}_*.toml')), name
