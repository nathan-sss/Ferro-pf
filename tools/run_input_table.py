def unit_of(path):
    if path in UNITS:
        return UNITS[path]
    head = path.rsplit(".", 1)[0] + ".*"
    if head in UNITS:
        return UNITS[head]
    for suffix, unit in _SUFFIX_UNITS:
        if path.endswith(suffix):
            return unit
    return "—"


