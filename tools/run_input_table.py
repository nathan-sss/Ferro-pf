def splice(text, name, block):
    b, e = BEGIN.format(name), END.format(name)
    i, j = text.find(b), text.find(e)
    if i < 0 or j < 0 or j < i:
        raise SystemExit(f"run_input_table: {OUT_PATH} has no {b} / {e} markers")
    return text[:i] + block + text[j + len(e):]


def rewrite(text):
    for name in TABLES:
        text = splice(text, name, render(name))
    return text


_ROW = re.compile(r"^\| `([^`]+)`(?: \((\w+)\))? \|")
_BLOCK = re.compile(r"<!-- run_input_table:begin (\S+) -->(.*?)<!-- run_input_table:end \1 -->", re.S)


def doc_leaves(text):
    """[dotted schema path] of every row of every generated block of ``text`` (with repetitions)."""
    out = []
    for name, body in _BLOCK.findall(text):
        for line in body.splitlines():
            m = _ROW.match(line)
            if m:
                out.append(raw_id(name, m.group(1), m.group(2)))
    return out


def coverage_problems(text):
    """Problems between the schema and the manual: a key missing from the manual, listed twice, or not in the schema;
    a description for a key the schema lacks."""
    raw, doc = raw_leaves(), doc_leaves(text)
    problems = []
    problems += [f"schema key {p!r} is not in any generated table of the manual" for p in raw if p not in doc]
    problems += [f"the manual lists {p!r}, which the schema does not have" for p in dict.fromkeys(doc) if p not in raw]
    problems += [f"the manual lists {p!r} twice" for p in dict.fromkeys(doc) if doc.count(p) > 1]
    stale = [p for p in DESC if p not in raw and not (p.startswith("stage<*>.") and any(
        r.startswith("stage<") and r.split(".", 1)[1] == p.split(".", 1)[1] for r in raw))]
    problems += [f"DESC has an entry for {p!r}, which the schema does not have" for p in stale]
    problems += [f"schema key {p!r} has no description in DESC" for p in raw if _desc(p) is None]
    return problems


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--emit", nargs="?", const="all", help="print the block of one table (or all); write nothing")
    ap.add_argument("--check", action="store_true", help="exit 1 if the manual is stale or incomplete")
    args = ap.parse_args()
    if args.emit:
        names = TABLES if args.emit == "all" else (args.emit,)
        for name in names:
            print(render(name), end="\n\n")
        return 0
    with open(OUT_PATH, encoding="utf-8") as fh:
        current = fh.read()
    updated = rewrite(current)
    problems = coverage_problems(updated)
    if args.check:
        if problems:
            print("run_input_table: PROBLEMS\n  " + "\n  ".join(problems))
            return 1
        if current != updated:
            print(f"run_input_table: STALE -- rerun tools/run_input_table.py ({OUT_PATH})")
            return 1
        print(f"run_input_table: up to date ({OUT_PATH})")
        return 0
    if problems:
        print("run_input_table: PROBLEMS\n  " + "\n  ".join(problems))
        return 1
    with open(OUT_PATH, "w", encoding="utf-8") as fh:
        fh.write(updated)
    print(f"run_input_table: wrote {len(TABLES)} tables into {OUT_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
