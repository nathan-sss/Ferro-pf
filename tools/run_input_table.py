def raw_id(table, key, variant):
    """The dotted schema path of a row of table ``table`` (the inverse of the layout above)."""
    if table.startswith("stage."):
        return f"stage<{table.split('.', 1)[1]}>.{key}"
    if table == "start":
        return f"stage.start<{variant}>.{key}" if variant else f"stage.start.{key}"
    if table == "field":
        return f"field<{variant}>.{key}" if variant else f"field.{key}"
    return f"{table}.{key}"


