"""RUN-ENTRY E5 (SPEC § 16.5) -- generate the key tables of docs/RUN_INPUT.md from fftpf.run_input.SCHEMA.

    python3 tools/run_input_table.py            # rewrite every generated block of docs/RUN_INPUT.md
    python3 tools/run_input_table.py --emit [name]   # print the blocks (or one), touch nothing
    python3 tools/run_input_table.py --check    # exit 1 if a block is stale, a marker is missing,
                                                # a schema key has no description, or a block names a key
                                                # that the schema does not have

WHY IT IS GENERATED.  The key, type, range, choices and default of every input key are read from
``run_input.SCHEMA`` (and the stage / field / start variants), so a new key, a changed default or a changed
range shows up in the manual without anybody typing it.  What a schema cannot carry -- the meaning of a key and
its unit where the key name does not state it -- lives in ``DESC`` / ``UNITS`` below, keyed by the schema path.
A schema key without a ``DESC`` entry makes ``--check`` (and the plain rewrite) fail, so a key cannot go
undocumented; a ``DESC`` entry for a key the schema no longer has fails too.

MARKERS.  Each table sits between a pair of comment lines in docs/RUN_INPUT.md

    <!-- run_input_table:begin NAME -->  ...  <!-- run_input_table:end NAME -->

where NAME is one of ``TABLES`` below.  Never hand-edit inside the markers; fix ``DESC`` / the schema and rerun.

PATH NAMES.  A schema path is a dotted key path.  A key that exists for one value of a discriminator carries
it in angle brackets: ``stage<hold>.n_steps`` (stage kind), ``stage.start<random>.amplitude`` (start kind),
``field<gaussian>.sigma_K`` (field kind).  ``raw_leaves()`` walks the schema generically (it knows nothing of
TABLES) and ``doc_leaves(text)`` reads the same names back from the rows of the generated blocks, so
``coverage_problems`` proves the manual lists every schema key once and nothing else.
"""
