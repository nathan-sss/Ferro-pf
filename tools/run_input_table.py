# --------------------------------------------------------------------------- what the schema is, flattened

def _walk(spec, path, out):
    """Generic walk: (dotted path with <variant> markers, V) for every leaf below ``spec``."""
    if isinstance(spec, ri.V):
        out.append((path, spec))
        return
    for key, sub in spec.fields.items():
        _walk(sub, f"{path}.{key}" if path else key, out)
    for variant, fields in (spec.variants or {}).items():
        for key, sub in fields.items():
            _walk(sub, f"{path}<{variant}>.{key}", out)


def raw_leaves():
    """{dotted path: V} of every leaf of the input file, from SCHEMA, the stage table and the field table."""
    out = []
    for top, spec in ri.SCHEMA.items():
        _walk(spec, top, out)
    _walk(ri._STAGE, "stage", out)
    _walk(ri._FIELD, "field", out)
    return dict(out)


# --------------------------------------------------------------------------- which table shows which keys

def _rows_of(spec):
    """[(key, variant, V)] of one schema Table: its own fields (nested tables as dotted keys), then its variants."""
    rows = []

    def own(sp, prefix):
        for key, sub in sp.fields.items():
            if isinstance(sub, ri.V):
                rows.append((prefix + key, None, sub))
            else:
                own(sub, prefix + key + ".")
    own(spec, "")
    for variant, fields in (spec.variants or {}).items():
        for key, sub in fields.items():
            if isinstance(sub, ri.V):
                rows.append((key, variant, sub))
            else:
                for k2, s2 in sub.fields.items():
                    rows.append((f"{key}.{k2}", variant, s2))
    return rows


def _table(name):
    S = ri.SCHEMA
    if name == "run":
        return _rows_of(S["run"])
    if name == "material":
        return [(k, None, v) for k, v in S["material"].fields.items() if isinstance(v, ri.V)]
    if name.startswith("material."):
        return _rows_of(S["material"].fields[name.split(".", 1)[1]])
    if name in ("geometry", "numerics", "output"):
        return _rows_of(S[name])
    if name.startswith("physics."):
        return _rows_of(S["physics"].fields[name.split(".", 1)[1]])
    if name == "measure":
        return [(k, None, v) for k, v in S["measure"].fields.items() if isinstance(v, ri.V)]
    if name.startswith("measure."):
        return _rows_of(S["measure"].fields[name.split(".", 1)[1]])
    if name == "stage":
        return [("kind", None, ri._STAGE.fields["kind"])]
    if name == "start":
        return _rows_of(ri._STAGE.fields["start"])
    if name == "field":
        return _rows_of(ri._FIELD)
    raise KeyError(name)


def _stage_rows(kind):
    """Rows of the stage variant ``kind`` (nested tables as dotted keys)."""
    rows = []
    for key, sub in ri._STAGE_VARIANTS[kind].items():
        if isinstance(sub, ri.V):
            rows.append((key, None, sub))
        else:
            rows += [(f"{key}.{k}", None, v) for k, v in sub.fields.items()]
    return rows


def rows(name):
    if name.startswith("stage."):
        return _stage_rows(name.split(".", 1)[1])
    return _table(name)


